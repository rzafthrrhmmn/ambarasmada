    public static function getByTingkatan(string $tingkatan): array
    {
        return match ($tingkatan) {
            'Bantara' => self::BANTARA,
            'Laksana' => self::LAKSANA,
            default => [],
        };
    }

    public static function getTotalByTingkatan(string $tingkatan): int
    {
        return count(self::getByTingkatan($tingkatan));
    }

    public static function getDescription(string $tingkatan, int $nomorPoin): ?string
    {
        $points = self::getByTingkatan($tingkatan);

        return $points[$nomorPoin] ?? null;
    }

    public static function all(): array
    {
